"""Builds physical dbt project structures on disk from ProjectState artifacts."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Dict

from backend.file_manager import FileManager
from config.settings import get_settings

logger = logging.getLogger(__name__)


class ProjectBuilder:
    """Takes generated SQL, YAML, tests, and docs from ProjectState and writes a complete dbt project."""

    def __init__(self, base_output_dir: Path | str | None = None) -> None:
        settings = get_settings()
        self.output_root = Path(base_output_dir or settings.project_output_dir).resolve()
        self.output_root.mkdir(parents=True, exist_ok=True)
        self.file_manager = FileManager(self.output_root)

    def build_project(self, state: Dict[str, Any]) -> str:
        """Create the dbt project directory tree and write all generated files.

        Returns the absolute path to the generated project directory.
        """
        project_name = state.get("project_name", "unnamed_dbt_project").strip()
        if not project_name:
            project_name = "dbt_project"

        # Sanitize project name
        project_slug = "".join(c if c.isalnum() or c in ("_", "-") else "_" for c in project_name).lower()
        project_dir = self.output_root / project_slug
        project_dir.mkdir(parents=True, exist_ok=True)

        logger.info("Building dbt project '%s' at %s", project_slug, project_dir)
        proj_fm = FileManager(project_dir)

        # Standard dbt directories
        for sub_dir in ["models", "analyses", "macros", "seeds", "snapshots", "tests"]:
            proj_fm.create_directory(sub_dir)

        # 1. Write SQL Models
        generated_models: Dict[str, str] = state.get("generated_models", {})
        for rel_path, content in generated_models.items():
            proj_fm.write_file(rel_path, content)

        # 2. Write YAML configurations
        generated_yaml: Dict[str, str] = state.get("generated_yaml", {})
        for rel_path, content in generated_yaml.items():
            proj_fm.write_file(rel_path, content)

        # 3. Write Tests
        generated_tests: Dict[str, str] = state.get("generated_tests", {})
        for rel_path, content in generated_tests.items():
            proj_fm.write_file(rel_path, content)

        # 4. Write Docs
        generated_docs: Dict[str, str] = state.get("generated_docs", {})
        for rel_path, content in generated_docs.items():
            proj_fm.write_file(rel_path, content)

        # 5. Default files if not generated by agents
        if not proj_fm.file_exists("README.md"):
            readme_content = f"# {project_name}\n\n"
            readme_content += state.get("project_description", "Generated by dbt Project Factory") + "\n\n"
            readme_content += "## Getting Started\n\n```bash\npip install dbt-snowflake\ndbt deps\ndbt parse\ndbt compile\n```\n"
            proj_fm.write_file("README.md", readme_content)

        if not proj_fm.file_exists(".gitignore"):
            proj_fm.write_file(".gitignore", "target/\ndbt_packages/\nlogs/\n*.pyc\n.env\n")

        if not proj_fm.file_exists("requirements.txt"):
            proj_fm.write_file("requirements.txt", "dbt-core>=1.8.0\ndbt-snowflake>=1.8.0\n")

        abs_path = str(project_dir.resolve())
        state["project_output_path"] = abs_path
        logger.info("Successfully built project '%s' at %s", project_slug, abs_path)
        return abs_path

